import { seriesExercise as exercise, type SeriesExercise, type SeriesLesson } from '../tenVersionTypes';

// Three task forms per lesson; each form has three declared parameter variants.
// These are original worked exercises, not different methods or attributed exam questions.
const variants = (label: string, make: (n: number) => SeriesExercise) => [1, 2, 3].map(n => ({
  ...make(n), variantLabel: `${label}（参数 ${n}）`,
}));
function lesson(courseId: SeriesLesson['courseId'], key: string, titleZh: string, title: string,
  definition: string, intuition: string, prerequisites: string[], notes: string[],
  latex: string, conditions: string, explanation: string, exercises: SeriesExercise[]): SeriesLesson {
  return { courseId, key, titleZh, title, summary: intuition, definition, intuition, prerequisites,
    learningNotes: notes, sourceNote: '原创练习；每个主题含三种任务形式，每种形式含三个已标注的参数变式。',
    formula: { title, titleZh, latex, conditions, explanation }, exercises };
}

